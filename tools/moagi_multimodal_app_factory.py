from __future__ import annotations
try:
    import torch
    import torch.nn as nn
except ImportError as exc:
    raise RuntimeError("Install optional AI dependencies: python manage.py install --ai") from exc

class AutoEncoder3D(nn.Module):
    def __init__(self, channels=1, base=16, latent=32):
        super().__init__()
        self.encoder = nn.Sequential(
            nn.Conv3d(channels, base, 4, 2, 1), nn.GELU(),
            nn.Conv3d(base, base * 2, 4, 2, 1), nn.GELU(),
            nn.Conv3d(base * 2, latent, 4, 2, 1), nn.GELU())
        self.decoder = nn.Sequential(
            nn.ConvTranspose3d(latent, base * 2, 4, 2, 1), nn.GELU(),
            nn.ConvTranspose3d(base * 2, base, 4, 2, 1), nn.GELU(),
            nn.ConvTranspose3d(base, channels, 4, 2, 1), nn.Sigmoid())

    def encode(self, x):
        return self.encoder(x)

    def decode(self, z):
        return self.decoder(z)

    def forward(self, x):
        z = self.encode(x)
        return self.decode(z), z

    @torch.no_grad()
    def refine(self, z, steps=2, alpha=0.35):
        for _ in range(max(0, steps)):
            z = (1.0 - alpha) * z + alpha * self.encode(self.decode(z))
        return z
