@dataclass
class AppSpec:
    name: str
    package: str
    title: str
    version: str = "0.1.0"
    description: str = "Jarvis-X generated multimodal multimedia application"

    @classmethod
    def from_name(cls, name: str) -> "AppSpec":
        clean = re.sub(r"[^A-Za-z0-9_]+", "_", name.strip()).strip("_") or "jarvisx_multimodal_app"
        if clean[0].isdigit():
            clean = "app_" + clean
        return cls(clean, clean.lower(), clean.replace("_", " ").title())


