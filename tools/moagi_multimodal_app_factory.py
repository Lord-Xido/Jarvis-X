#!/usr/bin/env python3
from __future__ import annotations
import argparse, subprocess, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PACKAGE = "__PKG__"
VERSION = "__VERSION__"

def run(cmd):
    print("+", " ".join(map(str, cmd)))
    subprocess.run(cmd, cwd=ROOT, check=True)

def package_release():
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    out = dist / f"{PACKAGE}-{VERSION}.zip"
    excluded = {"__pycache__", ".pytest_cache", "dist", ".git", ".venv", "venv"}
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in ROOT.rglob("*"):
            if path.is_dir():
                continue
            rel = path.relative_to(ROOT)
            if any(part in excluded for part in rel.parts):
                continue
            zf.write(path, rel)
    print("release:", out)

def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("install"); p.add_argument("--ai", action="store_true")
    sub.add_parser("test")
    sub.add_parser("package")
    p = sub.add_parser("run")
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=8000)
    p.add_argument("--reload", action="store_true")
    args = ap.parse_args()

    if args.cmd == "install":
        run([sys.executable, "-m", "pip", "install", "-r", "requirements.txt"])
        if args.ai:
            run([sys.executable, "-m", "pip", "install", "-r", "requirements-ai.txt"])
    elif args.cmd == "test":
        # Keep generated-project tests independent of parent pytest addopts.
        run([sys.executable, "-m", "pytest", "-q", "-o", "addopts=", "tests"])
    elif args.cmd == "package":
        package_release()
    elif args.cmd == "run":
        cmd = [sys.executable, "-m", "uvicorn", f"{PACKAGE}.app:app",
               "--host", args.host, "--port", str(args.port)]
        if args.reload:
            cmd.append("--reload")
        run(cmd)

if __name__ == "__main__":
    main()
