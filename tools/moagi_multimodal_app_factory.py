@app.post("/api/image")
async def image(file: UploadFile = File(...),
                transform: Literal["none","grayscale","thumbnail","mirror","autocontrast"] = Query("none"),
                return_image: bool = Query(False)):
    data = await file.read()
    try:
        with Image.open(BytesIO(data)) as im:
            original = im.size
            if transform == "grayscale":
                out = ImageOps.grayscale(im)
            elif transform == "thumbnail":
                out = im.copy(); out.thumbnail((768, 768))
            elif transform == "mirror":
                out = ImageOps.mirror(im)
            elif transform == "autocontrast":
                out = ImageOps.autocontrast(im.convert("RGB"))
            else:
                out = im.copy()
            arr = np.asarray(out.convert("RGB"), dtype=np.float32)
            mean = [round(float(v), 3) for v in arr.mean(axis=(0,1))]
            buf = BytesIO(); out.convert("RGB").save(buf, format="PNG"); encoded = buf.getvalue()
    except Exception as exc:
        raise HTTPException(400, f"image decode failed: {exc}") from exc
    if return_image:
        return Response(encoded, media_type="image/png")
    return {"modality":"image", "original_size":list(original), "output_size":list(out.size),
            "transform":transform, "mean_rgb":mean, "sha256":digest(data)}

@app.post("/api/audio")
async def audio(file: UploadFile = File(...)):
    data = await file.read()
    result = {"modality":"audio", "filename":file.filename, "bytes":len(data), "sha256":digest(data)}
    try:
        with wave.open(BytesIO(data), "rb") as wav:
            frames, rate = wav.getnframes(), wav.getframerate()
            result.update(format="wav", channels=wav.getnchannels(), sample_rate_hz=rate,
                          frames=frames, duration_seconds=round(frames/rate if rate else 0.0, 6))
    except Exception:
        result["format"] = "unknown-or-compressed"
    return result

@app.post("/api/video")
async def video(file: UploadFile = File(...)):
    data = await file.read()
    result = {"modality":"video", "filename":file.filename, "bytes":len(data), "sha256":digest(data)}
    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        result["probe"] = "ffprobe-unavailable"
        return result
    with tempfile.TemporaryDirectory() as td:
        path = Path(td) / ("input" + (Path(file.filename or "").suffix or ".bin"))
        path.write_bytes(data)
        proc = subprocess.run([ffprobe, "-v", "quiet", "-print_format", "json",
                               "-show_format", "-show_streams", str(path)],
                              capture_output=True, text=True)
    if proc.returncode:
        result["probe"] = "unreadable"
        return result
    try:
        probe = json.loads(proc.stdout)
    except json.JSONDecodeError:
        result["probe"] = "invalid-json"
        return result
    result["streams"] = probe.get("streams", [])
    result["format"] = probe.get("format", {})
    return result

@app.post("/api/volume")
async def volume(file: UploadFile = File(...)):
    data = await file.read()
    try:
        arr = np.load(BytesIO(data), allow_pickle=False)
        if arr.ndim not in (3,4,5) or not np.issubdtype(arr.dtype, np.number):
            raise ValueError("expected numeric 3D/4D/5D NumPy array")
        x = np.asarray(arr, dtype=np.float32)
        x = np.where(np.isfinite(x), x, 0.0)
    except Exception as exc:
        raise HTTPException(400, f"3D volume decode failed: {exc}") from exc
    nz = int(np.count_nonzero(x))
    return {"modality":"volume3d", "shape":list(x.shape), "elements":int(x.size),
            "min":float(x.min()) if x.size else 0.0, "max":float(x.max()) if x.size else 0.0,
            "mean":float(x.mean()) if x.size else 0.0,
            "sparsity":float(1.0 - nz/max(x.size,1)), "sha256":digest(data)}
