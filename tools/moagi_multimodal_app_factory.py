def render(text: str, spec: AppSpec) -> str:
    mapping = {
        "__PKG__": spec.package,
        "__TITLE__": spec.title,
        "__VERSION__": spec.version,
        "__DESCRIPTION__": spec.description,
        "__DIST__": spec.package.replace("_", "-"),
    }
    for key, value in mapping.items():
        text = text.replace(key, value)
    return textwrap.dedent(text).lstrip("\n")


def write_project(root: Path, spec: AppSpec, force: bool = False) -> None:
    if root.exists() and any(root.iterdir()) and not force:
        raise SystemExit(f"destination is not empty: {root}; use --force to overwrite generated files")
    root.mkdir(parents=True, exist_ok=True)
    for rel, body in TEMPLATES.items():
        path = root / render(rel, spec)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(body, spec), encoding="utf-8")
    for folder in ("uploads", "outputs", "checkpoints"):
        (root / folder).mkdir(exist_ok=True)
    (root / "app_spec.json").write_text(json.dumps(asdict(spec), indent=2), encoding="utf-8")


def validate_python(root: Path) -> None:
    failures = []
    for path in root.rglob("*.py"):
        if "__pycache__" in path.parts:
            continue
        try:
            py_compile.compile(str(path), doraise=True)
        except Exception as exc:
            failures.append((path, exc))
    if failures:
        for path, exc in failures:
            print("FAIL", path, exc)
        raise SystemExit(2)


def release_zip(root: Path, spec: AppSpec) -> Path:
    dist = root / "dist"
    dist.mkdir(exist_ok=True)
    out = dist / f"{spec.package}-{spec.version}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in root.rglob("*"):
            if path.is_dir() or "dist" in path.relative_to(root).parts or "__pycache__" in path.parts:
                continue
            zf.write(path, path.relative_to(root))
    return out


def add_create_args(p: argparse.ArgumentParser) -> None:
    p.add_argument("name")
    p.add_argument("--output")
    p.add_argument("--title")
    p.add_argument("--version", default="0.1.0")
    p.add_argument("--description", default="Jarvis-X generated multimodal multimedia application")
    p.add_argument("--force", action="store_true")


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate end-to-end multimodal/multimedia Python applications")
    sub = ap.add_subparsers(dest="command", required=True)
    p = sub.add_parser("create"); add_create_args(p)
    p = sub.add_parser("all"); add_create_args(p)
    p = sub.add_parser("validate"); p.add_argument("project")
    p = sub.add_parser("package"); p.add_argument("project")
    args = ap.parse_args()

    if args.command in {"create", "all"}:
        spec = AppSpec.from_name(args.name)
        if args.title:
            spec.title = args.title
        spec.version = args.version
        spec.description = args.description
        root = Path(args.output or spec.name).resolve()
        write_project(root, spec, args.force)
        validate_python(root)
        if args.command == "all":
            print("release:", release_zip(root, spec))
        print("generated:", root)
        return

    root = Path(args.project).resolve()
    validate_python(root)
    if args.command == "package":
        spec_path = root / "app_spec.json"
        if not spec_path.exists():
            raise SystemExit("app_spec.json not found")
        print("release:", release_zip(root, AppSpec(**json.loads(spec_path.read_text(encoding="utf-8")))))


if __name__ == "__main__":
    main()
