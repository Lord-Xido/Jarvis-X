def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def text_stats(text: str):
    words = text.split()
    freq = Counter(w.strip(".,!?;:'\"()[]{}").lower() for w in words)
    freq.pop("", None)
    return {"modality":"text", "characters":len(text), "words":len(words),
            "unique_words":len(freq), "top_words":freq.most_common(12), "preview":text[:500]}

