#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
CXX="${CXX:-g++}"
mkdir -p run
"$CXX" -std=c++20 -O2 -Wall -Wextra -Wpedantic dm3d_isa.cpp -o run/dm3d_isa
run/dm3d_isa --self-test
run/dm3d_isa --demo --out run/demo
run/dm3d_isa --quine > run/quine_check.txt
run/dm3d_isa --bench 32 | tee run/bench_result.txt
run/dm3d_isa --encode run/demo.recovered.raw run/roundtrip.dm3d
run/dm3d_isa --decode run/roundtrip.dm3d run/roundtrip.raw
cmp run/demo.recovered.raw run/roundtrip.raw
printf '\nSUCCESS: generated bytecode, capsule, raw reconstruction, quine and benchmark under ./run/\n'
