final class NeuralArenaDeviceHarness {
    private let device: MTLDevice
    private let queue: MTLCommandQueue
    private let direct: MTLComputePipelineState
    private let tiled: MTLComputePipelineState

    init() throws {
        guard let d = MTLCreateSystemDefaultDevice() else { throw ArenaFailure.noDevice }
        guard let q = d.makeCommandQueue() else { throw ArenaFailure.noDevice }
        guard let library = d.makeDefaultLibrary() else { throw ArenaFailure.noMetalLibrary }
        guard let f1 = library.makeFunction(name: "arena_q12_direct") else {
            throw ArenaFailure.missingKernel("arena_q12_direct")
        }
        guard let f2 = library.makeFunction(name: "arena_q12_tiled") else {
            throw ArenaFailure.missingKernel("arena_q12_tiled")
        }
        let p1 = try d.makeComputePipelineState(function: f1)
        let p2 = try d.makeComputePipelineState(function: f2)
        guard min(p1.maxTotalThreadsPerThreadgroup, p2.maxTotalThreadsPerThreadgroup) >= 256 else {
            throw ArenaFailure.threadgroupLimit
        }
        device=d;queue=q;direct=p1;tiled=p2
    }

    static func hardwareModel() -> String {
        var size=0
        guard sysctlbyname("hw.machine", nil, &size, nil, 0) == 0, size>0 else {return "unavailable"}
        var bytes=[CChar](repeating: 0, count: size)
        let rc=bytes.withUnsafeMutableBufferPointer { ptr in
            sysctlbyname("hw.machine", ptr.baseAddress, &size, nil, 0)
        }
        return rc == 0 ? String(cString: bytes) : "unavailable"
    }
    private static func linear(_ x:Int,_ y:Int,_ z:Int,_ spec:ArenaSpec)->Int {
        return x + spec.x * (y + spec.y * z)
    }
    static func makeField(_ spec: ArenaSpec) -> [Int16] {
        var state: UInt32=0x0A17C0DE
        var values=[Int16](repeating:0, count:spec.x*spec.y*spec.z*3)
        for z in 0..<spec.z {for y in 0..<spec.y {for x in 0..<spec.x {for c in 0..<3 {
            state ^= state &<< 13
            state ^= state >> 17
            state ^= state &<< 5
            var val = Int(state % 8193) - 4096
            if spec.pattern == 1 {
                val = (x == spec.x/2 && y == spec.y/2 && z == spec.z/2) ? (c == 1 ? -4096 : 4096) : 0
            } else if spec.pattern == 2 {
                val = -4096
            } else if spec.pattern == 3 {
                val = ((x+y+z+c)%2 == 1) ? 4096 : -4096
            }
            values[3*linear(x,y,z,spec)+c]=Int16(val)
        }}}}
        return values
    }
    @inline(__always) static func signedRoundDiv(_ n:Int32,_ d:Int32)->Int32 {
        return n >= 0 ? (n+d/2)/d : -((-n+d/2)/d)
    }
    static func cpuStep(_ input:[Int16],_ s:ArenaSpec)->[Int16] {
        let nx=s.x,ny=s.y,nz=s.z, xy=nx*ny
        var output=[Int16](repeating:0,count:input.count)
        for z in 0..<nz {for y in 0..<ny {for x in 0..<nx {
            let p=x+nx*(y+ny*z)
            for c in 0..<3 {
                let v=Int32(input[3*p+c])
                var sum:Int32=0
                var n:Int32=0
                if x>0 {sum+=Int32(input[3*(p-1)+c]);n+=1}
                if x+1<nx {sum+=Int32(input[3*(p+1)+c]);n+=1}
                if y>0 {sum+=Int32(input[3*(p-nx)+c]);n+=1}
                if y+1<ny {sum+=Int32(input[3*(p+nx)+c]);n+=1}
                if z>0 {sum+=Int32(input[3*(p-xy)+c]);n+=1}
                if z+1<nz {sum+=Int32(input[3*(p+xy)+c]);n+=1}
                let avg=n>0 ? signedRoundDiv(sum,n) : v
                let raw=signedRoundDiv(17*v+3*avg,20)
                output[3*p+c]=Int16(min(4096,max(-4096,raw)))
            }
        }}}
        return output
    }
    static func digest(_ input:[Int16])->String {
        var data=Data(capacity:input.count*2)
        for value in input {
            var v=value.littleEndian
            withUnsafeBytes(of:&v){data.append(contentsOf:$0)}
        }
        return SHA256.hash(data:data).map{String(format:"%02x",$0)}.joined()
    }
    static func mismatches(_ expected:[Int16],_ actual:[Int16],_ s:ArenaSpec)->String? {
        if expected.count != actual.count {return "length difference \(expected.count) != \(actual.count)"}
        for i in 0..<expected.count where expected[i] != actual[i] {
            let p=i/3, c=i%3
            let x=p%s.x, y=(p/s.x)%s.y,z=p/(s.x*s.y)
            let mask=UInt16(bitPattern:expected[i]) ^ UInt16(bitPattern:actual[i])
            return "first mismatch at (\(x),\(y),\(z)) channel \(c), expected \(expected[i]), got \(actual[i]), XOR 0x\(String(mask,radix:16)), changedBits \(mask.nonzeroBitCount)"
        }
        return nil
    }
    func gpuStep(_ input:[Int16],_ s:ArenaSpec, tiledMode:Bool) throws -> ([Int16],Double,Double?) {
        guard input.count == s.x*s.y*s.z*3, input.count>0 else {throw ArenaFailure.malformedCase}
        let length=input.count*MemoryLayout<Int16>.stride
        let a:MTLBuffer?=input.withUnsafeBytes { raw in
            guard let p=raw.baseAddress else {return nil}
            return device.makeBuffer(bytes:p,length:length,options:.storageModeShared)
        }
        guard let source=a,
              let destination=device.makeBuffer(length:length,options:.storageModeShared),
              let command=queue.makeCommandBuffer(),
              let encoder=command.makeComputeCommandEncoder() else {
            throw ArenaFailure.bufferAllocation
        }
        var dims=SIMD3<UInt32>(UInt32(s.x),UInt32(s.y),UInt32(s.z))
        encoder.setComputePipelineState(tiledMode ? tiled : direct)
        encoder.setBuffer(source,offset:0,index:0)
        encoder.setBuffer(destination,offset:0,index:1)
        encoder.setBytes(&dims,length:MemoryLayout<SIMD3<UInt32>>.stride,index:2)
        encoder.dispatchThreadgroups(
            MTLSize(width:(s.x+7)/8,height:(s.y+7)/8,depth:(s.z+3)/4),
            threadsPerThreadgroup:MTLSize(width:8,height:8,depth:4))
        encoder.endEncoding()
        let t=CFAbsoluteTimeGetCurrent()
        command.commit()
        command.waitUntilCompleted()
        let wallMS=(CFAbsoluteTimeGetCurrent()-t)*1000
        guard command.status == .completed else {
            throw ArenaFailure.commandFailure(command.error?.localizedDescription ?? String(describing:command.status))
        }
        let start=command.gpuStartTime,end=command.gpuEndTime
        let actualDeviceMS:Double?=(start>0 && end>=start) ? (end-start)*1000 : nil
        let ptr=destination.contents().bindMemory(to:Int16.self,capacity:input.count)
        return (Array(UnsafeBufferPointer(start:ptr,count:input.count)),wallMS,actualDeviceMS)
    }
    func run() -> ArenaDeviceReport {
        var evidence:[ArenaCaseEvidence]=[]
        var failures:[String]=[]
        for spec in GoldenArena.cases {
            var oracle=Self.makeField(spec)
            var directField=oracle, tiledField=oracle
            for iter in 1...spec.iterations {
                let cpuStart=CFAbsoluteTimeGetCurrent()
                oracle=Self.cpuStep(oracle,spec)
                let cpuMS=(CFAbsoluteTimeGetCurrent()-cpuStart)*1000
                let expectedDigest=GoldenArena.stepHashes[spec.name]?[iter-1] ?? "MISSING_GOLDEN"
                let cpuDigest=Self.digest(oracle)
                do {
                    let (d, directMS, directDeviceMS)=try gpuStep(directField,spec,tiledMode:false)
                    let (t, tiledMS, tiledDeviceMS)=try gpuStep(tiledField,spec,tiledMode:true)
                    directField=d;tiledField=t
                    let dh=Self.digest(d),th=Self.digest(t)
                    let first=Self.mismatches(oracle,d,spec)
                        ?? Self.mismatches(oracle,t,spec)
                    let failure = cpuDigest != expectedDigest
                        ? "CPU/GOLDEN mismatch \(cpuDigest) != \(expectedDigest)"
                        : first
                    if let f=failure {failures.append("\(spec.name) t\(iter): \(f)")}
                    evidence.append(ArenaCaseEvidence(
                        name:spec.name,dimensions:[spec.x,spec.y,spec.z],iteration:iter,
                        byteCount:oracle.count*2,expectedSHA256:expectedDigest,cpuSHA256:cpuDigest,
                        directGPUSHA256:dh,tiledGPUSHA256:th,pass:failure==nil,failure:failure,
                        cpuMilliseconds:cpuMS,directGPUWallMilliseconds:directMS,
                        tiledGPUWallMilliseconds:tiledMS,directGPUDeviceMilliseconds:directDeviceMS,
                        tiledGPUDeviceMilliseconds:tiledDeviceMS))
                } catch {
                    failures.append("\(spec.name) t\(iter): GPU error \(error)")
                    break
                }
            }
        }
        #if targetEnvironment(simulator)
        let isSimulator=true
        #else
        let isSimulator=false
        #endif
        let machine=Self.hardwareModel()
        let passed=evidence.filter{$0.pass}.count
        let success=failures.isEmpty && passed==GoldenArena.cases.reduce(0){$0+$1.iterations}
        return ArenaDeviceReport(
            schemaVersion:1,generatedUTC:ISO8601DateFormatter().string(from:Date()),
            hardwareModel:machine,iosVersion:UIDevice.current.systemVersion,
            gpuName:device.name,supportsAppleGPUFamily9:device.supportsFamily(.apple9),
            isSimulator:isSimulator,matchesIPhone15ProMax:machine=="iPhone16,2" && !isSimulator,
            metalThreadExecutionWidth:tiled.threadExecutionWidth,
            metalMaximumThreadsPerThreadgroup:tiled.maxTotalThreadsPerThreadgroup,
            casesPassed:passed,casesTotal:27,
            deviceBitwiseValidated:success && !isSimulator && machine=="iPhone16,2" && device.supportsFamily(.apple9),
            allComparisonsPassed:success,tests:evidence,exceptions:failures)
    }
}
