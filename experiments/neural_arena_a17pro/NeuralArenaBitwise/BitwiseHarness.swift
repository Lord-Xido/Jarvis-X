// NEURAL ARENA v1.3. CPU oracle + dual independent GPU kernels.
// The device report is evidence only after execution on the actual phone.
struct ArenaSpec {
    let name: String
    let x: Int
    let y: Int
    let z: Int
    let pattern: Int
    let iterations: Int
}

struct ArenaCaseEvidence: Codable {
    let name: String
    let dimensions: [Int]
    let iteration: Int
    let byteCount: Int
    let expectedSHA256: String
    let cpuSHA256: String
    let directGPUSHA256: String
    let tiledGPUSHA256: String
    let pass: Bool
    let failure: String?
    let cpuMilliseconds: Double
    let directGPUWallMilliseconds: Double
    let tiledGPUWallMilliseconds: Double
    let directGPUDeviceMilliseconds: Double?
    let tiledGPUDeviceMilliseconds: Double?
}
struct ArenaDeviceReport: Codable {
    let schemaVersion: Int
    let generatedUTC: String
    let hardwareModel: String
    let iosVersion: String
    let gpuName: String
    let supportsAppleGPUFamily9: Bool
    let isSimulator: Bool
    let matchesIPhone15ProMax: Bool
    let metalThreadExecutionWidth: Int
    let metalMaximumThreadsPerThreadgroup: Int
    let casesPassed: Int
    let casesTotal: Int
    let deviceBitwiseValidated: Bool
    let allComparisonsPassed: Bool
    let tests: [ArenaCaseEvidence]
    let exceptions: [String]
}

enum ArenaFailure: Error, CustomStringConvertible {
    case noDevice
    case noMetalLibrary
    case missingKernel(String)
    case threadgroupLimit
    case bufferAllocation
    case commandFailure(String)
    case malformedCase
    var description: String {
        switch self {
        case .noDevice: return "No MTLDevice available"
        case .noMetalLibrary: return "No compiled .metallib in app bundle"
        case .missingKernel(let s): return "Metal function missing: \(s)"
        case .threadgroupLimit: return "Device cannot run 256-thread workgroup"
        case .bufferAllocation: return "Metal buffer allocation failed"
        case .commandFailure(let s): return "Metal command failed: \(s)"
        case .malformedCase: return "Invalid case geometry or input length"
        }
    }
}

